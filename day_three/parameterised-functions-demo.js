function parameterisedFunctionOne(name) {
    console.log("Hello, " + name + "! This is a message from the parameterisedFunction.");
}
parameterisedFunctionOne("Alice");

function parameterisedFunctionTwo(a, b) {
    let sum = a+b;
    console.log("The sum of " + a + " and " + b + "  is " + sum);
}
parameterisedFunctionTwo(2,3);
